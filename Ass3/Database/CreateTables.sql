CREATE TABLE IF NOT EXISTS roles (
	role_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	role_name varchar(30) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS services (
	service_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	service_name varchar(120) NOT NULL UNIQUE,
	description text NOT NULL DEFAULT '',
	average_service_minutes integer NOT NULL CHECK (average_service_minutes > 0),
	is_active boolean NOT NULL DEFAULT true,
	created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS desks (
	desk_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	desk_name varchar(60) NOT NULL UNIQUE,
	status varchar(10) NOT NULL DEFAULT 'CLOSED' CHECK (status IN ('OPEN','PAUSED','CLOSED')),
	created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS users (
	user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	full_name varchar(160) NOT NULL,
	username varchar(80) NOT NULL UNIQUE,
	password_hash text NOT NULL,
	role_id integer NOT NULL REFERENCES roles(role_id),
	assigned_desk_id integer REFERENCES desks(desk_id),
	is_active boolean NOT NULL DEFAULT true,
	created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS taxpayers (
	taxpayer_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	full_name varchar(160) NOT NULL,
	registration_date timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS desk_services (
	desk_id integer NOT NULL REFERENCES desks(desk_id) ON DELETE CASCADE,
	service_id integer NOT NULL REFERENCES services(service_id) ON DELETE CASCADE,
	PRIMARY KEY (desk_id, service_id)
);

CREATE TABLE IF NOT EXISTS tickets (
	ticket_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	ticket_number varchar(30) NOT NULL UNIQUE,
	taxpayer_id integer NOT NULL REFERENCES taxpayers(taxpayer_id),
	service_id integer NOT NULL REFERENCES services(service_id),
	assigned_desk_id integer REFERENCES desks(desk_id),
	status varchar(15) NOT NULL DEFAULT 'WAITING' CHECK (status IN ('WAITING','CALLED','IN_SERVICE','SERVED','NO_SHOW','TRANSFERRED')),
	issued_at timestamptz NOT NULL DEFAULT now(),
	called_at timestamptz,
	service_started_at timestamptz,
	served_at timestamptz,
	CONSTRAINT ticket_times_check CHECK (served_at IS NULL OR served_at >= issued_at)
);

CREATE TABLE IF NOT EXISTS ticket_history (
	history_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	ticket_id bigint NOT NULL REFERENCES tickets(ticket_id) ON DELETE CASCADE,
	user_id integer REFERENCES users(user_id),
	action varchar(40) NOT NULL,
	details text NOT NULL DEFAULT '',
	created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS feedback (
	feedback_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	ticket_id bigint NOT NULL UNIQUE REFERENCES tickets(ticket_id) ON DELETE CASCADE,
	rating integer NOT NULL CHECK (rating BETWEEN 1 AND 5),
	comment text,
	created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS alerts (
	alert_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	alert_type varchar(40) NOT NULL,
	message text NOT NULL,
	ticket_id bigint REFERENCES tickets(ticket_id) ON DELETE SET NULL,
	is_read boolean NOT NULL DEFAULT false,
	created_at timestamptz NOT NULL DEFAULT now(),
	UNIQUE (alert_type, ticket_id)
);

CREATE TABLE IF NOT EXISTS activity_logs (
	log_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id integer REFERENCES users(user_id),
	action varchar(80) NOT NULL,
	description text NOT NULL DEFAULT '',
	created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS system_settings (
	setting_key varchar(80) PRIMARY KEY,
	setting_value varchar(200) NOT NULL
);
